    public static void register() {
        AF9Machines.multiblock("planetary_satellite", WorkableElectricMultiblockMachine::new, b -> b
                .langValue("Planetary Satellite")
                .rotationState(RotationState.NON_Y_AXIS)
                .recipeTypes(AF9Machines.type("neutron_collection"))
                .recipeModifiers(GTRecipeModifiers.PARALLEL_HATCH, GTRecipeModifiers.OC_NON_PERFECT,
                    GTRecipeModifiers.BATCH_MODE, AF9Modifiers.SATELLITE_YIELD)
                // one wear on the reflector a completed cycle: afterWorking is RecipeLogic.onRecipeFinish's first statement
                .afterWorking(machine -> AF9Modifiers.satelliteWear(machine))
                .appearanceBlock(AF9Machines.blockSupplier("af9:satellite_casing"))
                .tooltips(AF9Machines.lines("af9.planetary_satellite.tooltip.", 4))
                .pattern(definition -> {
                    var pattern = AF9Machines.aisles(FactoryBlockPattern.start(), SATELLITE_SHAPE);
                    return pattern
                        .where('S', Predicates.controller(Predicates.blocks(definition.get())))
                        .where(' ', Predicates.any())
                        .where('B', AF9Machines.blocks("gtceu:hsss_frame"))
                        .where('K', AF9Machines.blocks("gtceu:superconducting_coil"))
                        .where('C', AF9Machines.blocks("af9:satellite_casing")
                            .or(Predicates.abilities(PartAbility.INPUT_ENERGY).setMaxGlobalLimited(2, 1))
                            .or(Predicates.abilities(PartAbility.IMPORT_FLUIDS).setMaxGlobalLimited(2, 1))
                            .or(Predicates.abilities(PartAbility.IMPORT_ITEMS).setMaxGlobalLimited(1, 0))
                            .or(Predicates.abilities(PartAbility.EXPORT_FLUIDS).setMaxGlobalLimited(2, 1))
                            .or(Predicates.abilities(PartAbility.PARALLEL_HATCH).setMaxGlobalLimited(1, 1))
                            .or(Predicates.abilities(PartAbility.MAINTENANCE).setMaxGlobalLimited(1, 1)))
                        .build();
                })
                // the casing with GTNH's siphon face (kubejs assets, overlay_front*)
                .workableCasingModel(AF9Machines.rl("af9:block/satellite_casing"), AF9Machines.rl("gtceu:block/multiblock/planetary_satellite")));
    }
